#!/usr/bin/env python3
from __future__ import annotations

import argparse
import re
from pathlib import Path

import numpy as np
import tifffile


def strip_timestamp(name: str) -> str:
    """
    Remove trailing timestamp segment from acquisition folder name.
    Example:
      pollen-fov1-2xX-32.5mW_2026-04-17_17-25-47 -> pollen-fov1-2xX-32.5mW
    """
    return re.sub(r"_\d{4}-\d{2}-\d{2}_\d{2}-\d{2}-\d{2}$", "", name)


def mean_to_2d(stack: np.ndarray) -> np.ndarray:
    if stack.ndim == 2:
        return stack.astype(np.float32)
    if stack.ndim != 3:
        raise ValueError(f"Unsupported array shape: {stack.shape}")
    return stack.mean(axis=0, dtype=np.float32)


def load_tif(path: Path) -> np.ndarray:
    arr = tifffile.imread(path)
    if arr.ndim not in (2, 3):
        raise ValueError(f"Unsupported TIFF ndim={arr.ndim}: {path}")
    return arr


def process_sparse_preprocessed(preprocessed_root: Path, out_root: Path, overwrite: bool) -> None:
    mask_out = out_root / "mask"
    out_root.mkdir(parents=True, exist_ok=True)
    mask_out.mkdir(parents=True, exist_ok=True)

    restored_tifs = sorted(preprocessed_root.glob("*/CellVideo1/CellVideo/CellVideo_restored.tif"))
    if not restored_tifs:
        raise FileNotFoundError(f"No restored tif found under: {preprocessed_root}")

    for restored_path in restored_tifs:
        acq_name = restored_path.parents[2].name
        short_name = strip_timestamp(acq_name)
        mask_path = restored_path.with_name("CellVideo_mask.tif")
        if not mask_path.exists():
            raise FileNotFoundError(f"Mask not found for {restored_path}")

        img2d_path = out_root / f"{short_name}.tif"
        mask2d_path = mask_out / f"{short_name}_mask.tif"

        if img2d_path.exists() and mask2d_path.exists() and not overwrite:
            print(f"[Skip] Exists: {short_name}")
            continue

        restored = load_tif(restored_path)
        mask = load_tif(mask_path)

        img2d = mean_to_2d(restored)
        mask2d = mean_to_2d(mask)
        mask2d = (mask2d > 0.5).astype(np.uint8)

        tifffile.imwrite(img2d_path, img2d)
        tifffile.imwrite(mask2d_path, mask2d)
        print(f"[OK] Sparse 2D: {short_name} -> {img2d.shape}, mask -> {mask2d.shape}")


def process_gt_dense(data_root: Path, out_root: Path, overwrite: bool) -> None:
    mask_out = out_root / "mask"
    dense_tifs = sorted(data_root.glob("Sparse/*dense*/CellVideo1/CellVideo/*.tif"))
    if not dense_tifs:
        dense_tifs = sorted(data_root.glob("dense/*dense*/CellVideo1/CellVideo/*.tif"))
    if not dense_tifs:
        raise FileNotFoundError("No dense GT tif found in Sparse/*dense* or dense/*dense*.")

    for gt_path in dense_tifs:
        acq_name = gt_path.parents[2].name
        short_name = strip_timestamp(acq_name)
        img2d_path = out_root / f"{short_name}.tif"
        mask2d_path = mask_out / f"{short_name}_mask.tif"

        if img2d_path.exists() and mask2d_path.exists() and not overwrite:
            print(f"[Skip] Exists GT: {short_name}")
            continue

        gt = load_tif(gt_path)
        gt2d = mean_to_2d(gt)
        gt_mask2d = np.ones_like(gt2d, dtype=np.uint8)

        tifffile.imwrite(img2d_path, gt2d)
        tifffile.imwrite(mask2d_path, gt_mask2d)
        print(f"[OK] GT 2D: {short_name} -> {gt2d.shape}, mask -> {gt_mask2d.shape}")


def build_args() -> argparse.Namespace:
    parser = argparse.ArgumentParser(
        description=(
            "Build 2D pollen sparse dataset by averaging 100-frame stacks. "
            "Also exports corresponding 2D masks and includes GT dense 2D."
        )
    )
    parser.add_argument(
        "--data_root",
        type=Path,
        default=Path("/data2/wjb/threePM/ThreePM_openDatasets/pollen_test"),
        help="pollen_test root directory.",
    )
    parser.add_argument(
        "--preprocessed_root",
        type=Path,
        default=Path("/data2/wjb/threePM/ThreePM_openDatasets/pollen_test/preprocessed"),
        help="Directory generated by preprocess_pollen_sparse_restore.py.",
    )
    parser.add_argument(
        "--output_root",
        type=Path,
        default=Path("/data2/wjb/threePM/ThreePM_openDatasets/pollen_test/Sparse_Datasets"),
        help="Output dataset root.",
    )
    parser.add_argument(
        "--overwrite",
        action="store_true",
        help="Overwrite existing files.",
    )
    return parser.parse_args()


def main() -> None:
    args = build_args()
    process_sparse_preprocessed(args.preprocessed_root, args.output_root, args.overwrite)
    process_gt_dense(args.data_root, args.output_root, args.overwrite)
    print(f"[Done] 2D dataset saved to: {args.output_root}")


if __name__ == "__main__":
    main()
